export function generateW3CTokensJSON(seed: SeedConfig): string {
  const scale = computeTonalScale(seed.hue, seed.chroma);
  const primaryTokens: Record<string, { $value: string; $type: string }> = {};
  scale.forEach((s) => {
    primaryTokens[String(s.tone)] = {
      $value: s.oklch,
      $type: "color",
    };
  });

  return JSON.stringify(
    {
      $schema: "https://tr.designtokens.org/format/",
      meta: {
        system: "Antigravity Perceptual & Spatial Design System",
        preset: seed.name,
        colorSpace: "oklch",
      },
      reference: {
        primary: primaryTokens,
        secondary: {
          "40": { $value: `oklch(0.46 0.15 ${seed.secondaryHue})`, $type: "color" },
          "70": { $value: `oklch(0.74 0.14 ${seed.secondaryHue})`, $type: "color" },
        },
        tertiary: {
          "40": { $value: `oklch(0.45 0.14 ${seed.tertiaryHue})`, $type: "color" },
          "70": { $value: `oklch(0.76 0.15 ${seed.tertiaryHue})`, $type: "color" },
        },
      },
      system: {
        dark: {
          surfaceCanvas: { $value: `oklch(0.135 ${seed.neutralChroma} ${seed.hue})`, $type: "color" },
          surfaceContainer: { $value: `oklch(0.190 ${seed.neutralChroma} ${seed.hue})`, $type: "color" },
          primary: { $value: "{reference.primary.70}", $type: "color" },
        },
        light: {
          surfaceCanvas: { $value: `oklch(0.985 ${seed.neutralChroma} ${seed.hue})`, $type: "color" },
          surfaceContainer: { $value: `oklch(0.958 ${seed.neutralChroma} ${seed.hue})`, $type: "color" },
          primary: { $value: "{reference.primary.40}", $type: "color" },
        },
      },
    },
    null,
    2
  );
}

