export interface TonalStop {
  tone: number;
  lightness: number;
  chromaFactor: number;
  oklch: string;
  recommendedText: "light" | "dark";
  contrastVsDarkCanvas: string;
  contrastVsLightCanvas: string;
}

export function computeTonalScale(hue: number, baseChroma: number): TonalStop[] {
  const stepMap: { tone: number; l: number; cf: number }[] = [
    { tone: 0, l: 0.0, cf: 0.0 },
    { tone: 10, l: 0.2, cf: 0.65 },
    { tone: 20, l: 0.29, cf: 0.8 },
    { tone: 30, l: 0.38, cf: 0.92 },
    { tone: 40, l: 0.49, cf: 1.0 },
    { tone: 50, l: 0.59, cf: 1.0 },
    { tone: 60, l: 0.68, cf: 0.95 },
    { tone: 70, l: 0.77, cf: 0.8 },
    { tone: 80, l: 0.85, cf: 0.58 },
    { tone: 90, l: 0.92, cf: 0.32 },
    { tone: 95, l: 0.96, cf: 0.16 },
    { tone: 99, l: 0.99, cf: 0.05 },
    { tone: 100, l: 1.0, cf: 0.0 },
  ];

  return stepMap.map(({ tone, l, cf }) => {
    const c = Number((baseChroma * cf).toFixed(3));
    const oklch = `oklch(${l.toFixed(2)} ${c} ${hue})`;
    // Approximate relative luminance from OKLCH L (L^3 in Oklab)
    const relLum = Math.pow(l, 3);
    const darkCanvasLum = Math.pow(0.135, 3);
    const lightCanvasLum = Math.pow(0.985, 3);

    const ratioDark =
      (Math.max(relLum, darkCanvasLum) + 0.05) / (Math.min(relLum, darkCanvasLum) + 0.05);
    const ratioLight =
      (Math.max(relLum, lightCanvasLum) + 0.05) / (Math.min(relLum, lightCanvasLum) + 0.05);

    return {
      tone,
      lightness: l,
      chromaFactor: cf,
      oklch,
      recommendedText: l > 0.62 ? "dark" : "light",
      contrastVsDarkCanvas: `${ratioDark.toFixed(1)}:1`,
      contrastVsLightCanvas: `${ratioLight.toFixed(1)}:1`,
    };
  });
}

